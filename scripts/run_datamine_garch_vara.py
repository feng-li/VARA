def load_validated_har_vara_forecast(
    output_dir: Path,
    *,
    expected_shape: tuple[int, int],
    required_contract_fields: Mapping[str, object],
) -> np.ndarray:
    """Load a HAR--VARA comparator only after validating its provenance."""
    contract_path = output_dir / "forecasts" / "contract.json"
    forecast_path = output_dir / "forecasts" / "vara_final_forecast.npy"
    if not contract_path.exists():
        raise FileNotFoundError(contract_path)
    if not forecast_path.exists():
        raise FileNotFoundError(forecast_path)
    contract = json.loads(contract_path.read_text(encoding="utf-8"))
    for field, expected in required_contract_fields.items():
        if contract.get(field) != expected:
            raise ValueError(
                f"HAR--VARA comparator has {field}={contract.get(field)!r}; "
                f"expected {expected!r}."
            )
    forecast = np.load(forecast_path, mmap_mode="r")
    if forecast.shape != expected_shape:
        raise ValueError("HAR--VARA comparator forecast has the wrong panel shape.")
    return forecast


