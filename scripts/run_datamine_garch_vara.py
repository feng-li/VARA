def _save_float32_array(path: Path, values: np.ndarray) -> None:
    """Atomically save an array, including when ``values`` memory-maps ``path``."""
    temporary = path.with_name(f".{path.name}.tmp")
    with temporary.open("wb") as handle:
        np.save(handle, np.asarray(values, dtype=np.float32), allow_pickle=False)
    temporary.replace(path)


def _save_int64_array(path: Path, values: np.ndarray) -> None:
    """Atomically save integer indices that may memory-map ``path`` itself."""
    temporary = path.with_name(f".{path.name}.tmp")
    with temporary.open("wb") as handle:
        np.save(handle, np.asarray(values, dtype=np.int64), allow_pickle=False)
    temporary.replace(path)


def estimate_validation_log_offset(
    *,
    target: np.ndarray,
    garch_log_forecast: np.ndarray,
    reference_forecast: np.ndarray,
    validation_indices: np.ndarray,
) -> dict[str, float]:
    """Estimate one pooled GARCH log-risk offset on matched validation cells."""
    indices = np.asarray(validation_indices, dtype=np.int64)
    observed = np.asarray(target, dtype=float)[indices]
    forecast = np.asarray(garch_log_forecast, dtype=float)[indices]
    reference = np.asarray(reference_forecast, dtype=float)[indices]
    if observed.shape != forecast.shape or observed.shape != reference.shape:
        raise ValueError("target, GARCH forecast, and reference forecast must have one shape.")
    valid = np.isfinite(observed) & np.isfinite(forecast) & np.isfinite(reference)
    if not valid.any():
        raise ValueError("No matched validation cells are available for the GARCH offset.")
    raw_error = forecast[valid] - observed[valid]
    offset = float(np.mean(raw_error))
    adjusted_error = raw_error - offset
    return {
        "offset": offset,
        "validation_cells": int(valid.sum()),
        "raw_validation_bias": float(np.mean(raw_error)),
        "adjusted_validation_bias": float(np.mean(adjusted_error)),
        "raw_validation_rmse": float(np.sqrt(np.mean(np.square(raw_error)))),
        "adjusted_validation_rmse": float(np.sqrt(np.mean(np.square(adjusted_error)))),
    }


def combine_garch_vara_forecasts(
    *,
    base_forecast: np.ndarray,
    correction: np.ndarray,
    selected_lambda: float | np.ndarray,
    offset_model: str = GARCH_OFFSET_MODEL,
    unit_model: str = GARCH_VARA_UNIT_MODEL,
    lambda_model: str = GARCH_VARA_LAMBDA_MODEL,
) -> dict[str, np.ndarray]:
    """Compatibility wrapper around the shared VARA forecast combiner."""
    unit, weighted = combine_base_vara_forecasts(
        base_forecast=base_forecast,
        correction=correction,
        lambda_weights=selected_lambda,
    )
    return {
        str(offset_model): np.asarray(base_forecast, dtype=float),
        str(unit_model): unit,
        str(lambda_model): weighted,
    }


def derive_raw_garch_vara_unit(
    *,
    raw_base_forecast: np.ndarray,
    offset_correction: np.ndarray,
    offset: float,
) -> tuple[np.ndarray, np.ndarray]:
    """Derive the raw-GARCH VARA correction and its unit-weight forecast.

    ``rolling_har_vara_corrections`` is equivariant to a common additive shift
    of every response: its componentwise centers shift by the same constant,
    while its standardized responses, scales, attention lags, and fitted
    coefficients do not change. Raw-GARCH errors equal offset-GARCH errors
    minus ``offset``.
    Consequently this is exactly the result of refitting VARA on the raw-GARCH
    errors, apart from floating-point roundoff, without duplicating the costly
    rolling fit.
    """
    raw_base = np.asarray(raw_base_forecast, dtype=float)
    adjustment = np.asarray(offset_correction, dtype=float)
    if raw_base.shape != adjustment.shape:
        raise ValueError("raw_base_forecast and offset_correction must have the same shape.")
    raw_correction = adjustment - float(offset)
    return raw_correction, raw_base + raw_correction


def _correction_summary(
    error: np.ndarray,
    correction: np.ndarray,
    weight: float | np.ndarray,
) -> dict[str, float]:
    error_values = np.asarray(error, dtype=float)
    adjustment = np.asarray(correction, dtype=float)
    weight_values = np.asarray(weight, dtype=float)
    if weight_values.ndim > 0 and weight_values.shape != error_values.shape:
        raise ValueError("weight must be scalar or match the error shape.")
    valid = np.isfinite(error_values) & np.isfinite(adjustment) & np.isfinite(weight_values)
    if not valid.any():
        return {
            "cells": 0,
            "base_rmse": np.nan,
            "corrected_rmse": np.nan,
            "squared_error_reduction": np.nan,
        }
    base_sse = float(np.sum(np.square(error_values[valid])))
    weighted_adjustment = weight_values * adjustment
    corrected_error = error_values[valid] - weighted_adjustment[valid]
    corrected_sse = float(np.sum(np.square(corrected_error)))
    return {
        "cells": int(valid.sum()),
        "base_rmse": float(np.sqrt(base_sse / valid.sum())),
        "corrected_rmse": float(np.sqrt(corrected_sse / valid.sum())),
        "squared_error_reduction": 1.0 - corrected_sse / base_sse,
    }


def _dm_table(
    monthly: pd.DataFrame,
    *,
    offset_model: str = GARCH_OFFSET_MODEL,
    unit_model: str = GARCH_VARA_UNIT_MODEL,
    lambda_model: str = GARCH_VARA_LAMBDA_MODEL,
    raw_model: str = "garch11",
    raw_unit_model: str = RAW_GARCH_VARA_UNIT_MODEL,
) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    comparator_map = {
        str(unit_model): (str(offset_model), "baseline", "har_vara"),
        str(lambda_model): (str(offset_model), "baseline", "har_vara"),
        str(raw_unit_model): (
            str(raw_model),
            str(offset_model),
            "baseline",
            "har_vara",
        ),
    }
    for focal_name, comparator_names in comparator_map.items():
        focal = monthly.loc[monthly["model"].eq(focal_name)]
        for comparator_name in comparator_names:
            comparator = monthly.loc[monthly["model"].eq(comparator_name)]
            if focal.empty or comparator.empty:
                continue
            for loss in ("squared_error", "gaussian_return_crps"):
                matched = focal[["date", loss]].merge(
                    comparator[["date", loss]],
                    on="date",
                    suffixes=("_focal", "_comparator"),
                ).dropna()
                rows.append({
                    "focal_model": focal_name,
                    "comparator_model": comparator_name,
                    "loss": loss,
                    **diebold_mariano_test(
                        matched[f"{loss}_focal"],
                        matched[f"{loss}_comparator"],
                        forecast_horizon=1,
                    ),
                })
    return pd.DataFrame(rows)


